Set-Content -Path ".\NGROK_URLS.txt" -Value $urlsContent
Write-Host "📝 URLs saved to NGROK_URLS.txt" -ForegroundColor Green
Write-Host ""

# Monitor services
Write-Host "🔄 Monitoring services... (Press Ctrl+C to stop)" -ForegroundColor Cyan
Write-Host ""

try {
    while ($true) {
        Start-Sleep -Seconds 30
        
        # Check job status
        if ($backendJob.State -ne "Running") {
            Write-Host "⚠️  Backend stopped" -ForegroundColor Red
        }
        if ($frontendJob.State -ne "Running") {
            Write-Host "⚠️  Frontend stopped" -ForegroundColor Red
        }
        if ($ngrokJob.State -ne "Running") {
            Write-Host "⚠️  Ngrok stopped" -ForegroundColor Red
        }
    }
} finally {
    Write-Host ""
    Write-Host "🛑 Stopping all services..." -ForegroundColor Yellow
    
    Stop-Job $backendJob -ErrorAction SilentlyContinue
    Stop-Job $frontendJob -ErrorAction SilentlyContinue
    Stop-Job $ngrokJob -ErrorAction SilentlyContinue
    
    Remove-Job $backendJob -ErrorAction SilentlyContinue
    Remove-Job $frontendJob -ErrorAction SilentlyContinue
    Remove-Job $ngrokJob -ErrorAction SilentlyContinue
    
    Write-Host "✅ All services stopped" -ForegroundColor Green
    Write-Host ""
}
